# The same lines rendered by structlog, which formats records of the standard
# logging module as it formats its own.

import logging

import structlog


def formatter() -> logging.Formatter:
    return structlog.stdlib.ProcessorFormatter(
        # These run on each record logged through the logging module, such as
        # those of Dubbo: ExtraAdder adds the fields of the record.
        foreign_pre_chain=[
            structlog.processors.TimeStamper(fmt="iso", utc=True),
            structlog.stdlib.add_log_level,
            structlog.stdlib.add_logger_name,
            structlog.stdlib.ExtraAdder(),
        ],
        processors=[
            structlog.stdlib.ProcessorFormatter.remove_processors_meta,
            structlog.processors.format_exc_info,
            structlog.processors.JSONRenderer(),
        ],
    )
